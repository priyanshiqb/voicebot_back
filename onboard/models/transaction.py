from django.db import models
from utils.models.base_model_core import BaseModelCore
from django.conf import settings


class Transaction(BaseModelCore):
    """
    Transaction Model representing a record of payment attempts, order identifiers,
    and actual billing execution status integrated via Razorpay.
    """
    class TransactionStatusChoices(models.TextChoices):
        PENDING = "pending", "Pending"
        SUCCESSFUL = "successful", "Successful"
        FAILED = "failed", "Failed"
        CANCELED = "canceled", "Canceled"

    razorpay_order_id = models.CharField(
        max_length=255,
        unique=True,
        db_index=True,
        help_text="Unique payment order ID generated by Razorpay."
    )
    razorpay_payment_id = models.CharField(
        max_length=255,
        blank=True,
        null=True,
        db_index=True,
        help_text="Unique successful payment transaction ID generated by Razorpay."
    )
    amount = models.DecimalField(
        max_digits=10,
        decimal_places=2,
        help_text="Transaction monetary amount billed in INR."
    )
    status = models.CharField(
        max_length=20,
        choices=TransactionStatusChoices.choices,
        default=TransactionStatusChoices.PENDING,
        help_text="Current transaction execution status."
    )
    temp_user = models.ForeignKey(
        "onboard.TempUser",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="transactions",
        help_text="Reference to the pending onboard registrant."
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="transactions",
        help_text="Reference to the active CustomUser account."
    )
    plan = models.ForeignKey(
        "onboard.Plan",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="transactions",
        help_text="The target Plan selected for purchase."
    )
    raw_webhook_payload = models.JSONField(
        blank=True,
        null=True,
        help_text="Logged JSON response payloads from webhook events for debugging."
    )

    class Meta:
        db_table = "onboard_transaction"
        ordering = ["-created_at"]

    def __str__(self):
        return f"Order {self.razorpay_order_id} - {self.status} (INR {self.amount})"
